# render.sh — app.conf for one host from the template.

# render_host HOST POOL RELEASE — writes the file to stdout.
render_host() {
  local host=$1 pool=$2 release=$3 s val script=""
  for s in $(template_settings); do
    val=$(resolve "$host" "$pool" "$s") || { warn "no value for $s on $host"; return 1; }
    case "$val" in *$'\n'*) warn "multi-line value for $s on $host"; return 1 ;; esac
    script="${script}s|{{$s}}|$(sed_repl_escape "$val")|g;"
  done
  printf '# generated by rollout for %s (pool %s, release %s) — do not edit on the host\n' \
    "$host" "$pool" "$release"
  sed -e "$script" "$TEMPLATE"
}

# rendered_value FILE SETTING-LINE-KEY — value of "key = value" in a rendered file
rendered_value() {
  awk -v k="$2" '{ i = index($0, " = ") } i && substr($0, 1, i - 1) == k { print substr($0, i + 3); exit }' "$1"
}
