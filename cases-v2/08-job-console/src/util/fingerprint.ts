/** Cheap change detector for a list of lines (FNV-1a over content + count). */
export function fingerprint(lines: readonly string[]): string {
  let h = 0x811c9dc5;
  for (const line of lines) {
    for (let i = 0; i < line.length; i++) {
      h ^= line.charCodeAt(i);
      h = Math.imul(h, 0x01000193);
    }
    h ^= 0x0a;
    h = Math.imul(h, 0x01000193);
  }
  return `${lines.length}:${(h >>> 0).toString(16)}`;
}
